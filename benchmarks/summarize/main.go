// Command summarize turns the raw benchmark CSVs into
// benchmarks/results/summary.md: the median of the repeats for every
// (variant, concurrency) pair, the optimisation ladder, and the
// fault-tolerance run. Used by benchmarks/run.sh.
package main

import (
	"encoding/csv"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type row struct {
	label          string
	conc           int
	ops            float64
	p50, p99, p999 float64
}

func main() {
	dir := flag.String("dir", "benchmarks/results", "results directory")
	variants := flag.String("variants", "", "comma-separated variant labels, in ladder order")
	desc := flag.String("desc", "", "variant descriptions: label=text;label=text")
	env := flag.String("env", "", "file with hardware/OS/Go version lines")
	protocol := flag.String("protocol", "", "one-line description of the protocol")
	faults := flag.String("faults", "", "fault-tolerance summary file")
	out := flag.String("out", "benchmarks/results/summary.md", "output")
	flag.Parse()

	descs := map[string]string{}
	for _, d := range strings.Split(*desc, ";") {
		if k, v, ok := strings.Cut(d, "="); ok {
			descs[k] = v
		}
	}
	data := map[string]map[int][]row{}
	files, _ := filepath.Glob(filepath.Join(*dir, "raw", "*.csv"))
	for _, f := range files {
		for _, r := range readCSV(f) {
			if data[r.label] == nil {
				data[r.label] = map[int][]row{}
			}
			data[r.label][r.conc] = append(data[r.label][r.conc], r)
		}
	}
	labels := strings.Split(*variants, ",")
	var concs []int
	seen := map[int]bool{}
	for _, l := range labels {
		for c := range data[l] {
			if !seen[c] {
				seen[c] = true
				concs = append(concs, c)
			}
		}
	}
	sort.Ints(concs)

	var b strings.Builder
	fmt.Fprintf(&b, "# RaftKV benchmark results\n\n")
	fmt.Fprintf(&b, "Generated by `benchmarks/run.sh`. Raw per-run CSVs are in `benchmarks/results/raw/`.\n\n")
	if *env != "" {
		e, _ := os.ReadFile(*env)
		fmt.Fprintf(&b, "## Environment\n\n```\n%s```\n\n", e)
	}
	if *protocol != "" {
		fmt.Fprintf(&b, "## Protocol\n\n%s\n\n", *protocol)
	}

	final := labels[len(labels)-1]
	fmt.Fprintf(&b, "## Final configuration (`%s`)\n\n", final)
	fmt.Fprintf(&b, "| clients | ops/s (median) | p50 ms | p99 ms | p99.9 ms | runs |\n|---:|---:|---:|---:|---:|---:|\n")
	bestOps, bestConc, bestP99 := 0.0, 0, 0.0
	for _, c := range concs {
		rs := data[final][c]
		if len(rs) == 0 {
			continue
		}
		m := median(rs)
		fmt.Fprintf(&b, "| %d | %.0f | %.2f | %.2f | %.2f | %d |\n", c, m.ops, m.p50, m.p99, m.p999, len(rs))
		if m.ops > bestOps {
			bestOps, bestConc, bestP99 = m.ops, c, m.p99
		}
	}
	fmt.Fprintf(&b, "\n**Best sustained median: %.0f ops/s at %d clients, p99 %.2f ms at that point.**\n\n", bestOps, bestConc, bestP99)

	fmt.Fprintf(&b, "## Optimisation ladder\n\nEach row adds one change to the row above it. Median ops/s (p99 ms in brackets).\n\n")
	fmt.Fprintf(&b, "| step | change |")
	for _, c := range concs {
		if c == 1 {
			fmt.Fprintf(&b, " 1 client |")
		} else {
			fmt.Fprintf(&b, " %d clients |", c)
		}
	}
	fmt.Fprintf(&b, "\n|---|---|")
	for range concs {
		fmt.Fprintf(&b, "---:|")
	}
	fmt.Fprintf(&b, "\n")
	for i, l := range labels {
		fmt.Fprintf(&b, "| %d `%s` | %s |", i, l, descs[l])
		for _, c := range concs {
			rs := data[l][c]
			if len(rs) == 0 {
				fmt.Fprintf(&b, " – |")
				continue
			}
			m := median(rs)
			fmt.Fprintf(&b, " %.0f (%.1f) |", m.ops, m.p99)
		}
		fmt.Fprintf(&b, "\n")
	}
	if *faults != "" {
		f, err := os.ReadFile(*faults)
		if err == nil {
			fmt.Fprintf(&b, "\n## Fault tolerance\n\n%s\n", f)
		}
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Print(b.String())
}

// median takes the run with the median throughput and reports its numbers,
// with each latency percentile also taken as the median across runs.
func median(rs []row) row {
	pick := func(f func(row) float64) float64 {
		v := make([]float64, len(rs))
		for i, r := range rs {
			v[i] = f(r)
		}
		sort.Float64s(v)
		if len(v)%2 == 1 {
			return v[len(v)/2]
		}
		return (v[len(v)/2-1] + v[len(v)/2]) / 2
	}
	return row{
		ops:  pick(func(r row) float64 { return r.ops }),
		p50:  pick(func(r row) float64 { return r.p50 }),
		p99:  pick(func(r row) float64 { return r.p99 }),
		p999: pick(func(r row) float64 { return r.p999 }),
	}
}

func readCSV(path string) []row {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	recs, err := csv.NewReader(f).ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	var out []row
	for i, r := range recs {
		if i == 0 || len(r) < 6 {
			continue
		}
		c, _ := strconv.Atoi(r[1])
		ops, _ := strconv.ParseFloat(r[2], 64)
		p50, _ := strconv.ParseFloat(r[3], 64)
		p99, _ := strconv.ParseFloat(r[4], 64)
		p999, _ := strconv.ParseFloat(r[5], 64)
		out = append(out, row{label: r[0], conc: c, ops: ops, p50: p50, p99: p99, p999: p999})
	}
	return out
}
